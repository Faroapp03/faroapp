/** @param {keyof typeof ES} clave @param {Record<string,string|number>} [valores] */
export function textoHumano(clave, valores = {}) {
  const diccionario = idiomaActual() === 'ca' ? CA : ES;
  return diccionario[clave].replace(/\{(\w+)\}/gu, (marca, nombre) => String(valores[nombre] ?? marca));
}

